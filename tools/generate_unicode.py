"""Generate the runtime's pinned Unicode tables from Unicode 18.0 UCD.zip.

Usage: python3 tools/generate_unicode.py /path/to/UCD.zip
Source: https://www.unicode.org/Public/18.0.0/ucd/UCD.zip
Normal builds use committed tables and never fetch data.
"""
from pathlib import Path
import hashlib
import sys
import zipfile

root = Path(__file__).resolve().parents[1]
data = Path(sys.argv[1]).read_bytes()
if hashlib.sha256(data).hexdigest() != "7b3e555514060b92290d154f53655c5eb0fa62b16eb04c03434ff72d1a66a0d8":
    raise ValueError("expected the pinned final Unicode 18.0.0 UCD archive")
archive = zipfile.ZipFile(sys.argv[1])
classes = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
           "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]


def records(name):
    for line in archive.read(name).decode().splitlines():
        parts = [p.strip() for p in line.split("#")[0].split(";")]
        if len(parts) < 2:
            continue
        span = parts[0].split("..")
        yield int(span[0], 16), int(span[-1], 16), parts[1:]


tables = {"breaks": [(a, b, classes.index(p[0])) for a, b, p in records("auxiliary/GraphemeBreakProperty.txt")]}
tables["wide"] = [(a, b, 1) for a, b, p in records("EastAsianWidth.txt") if p[0] in ("W", "F")]
for table, prop in [("pictographic", "Extended_Pictographic"), ("emoji", "Emoji_Presentation")]:
    tables[table] = [(a, b, 1) for a, b, p in records("emoji/emoji-data.txt") if p[0] == prop]
tables["incb"] = [(a, b, {"Consonant": 1, "Extend": 2, "Linker": 3}[p[1]])
                  for a, b, p in records("DerivedCoreProperties.txt") if p[0] == "InCB"]
output = ["//! Generated by tools/generate_unicode.py; Unicode 18.0.0. See tests/unicode/LICENSE.txt.",
          "pub const version = \"18.0.0\";", "pub const Range = struct { first: u21, last: u21, value: u8 };",
          "pub const Break = enum(u8) { " + ", ".join(classes) + " };"]
for name, items in tables.items():
    merged = []
    for a, b, value in sorted(items):
        if merged and merged[-1][1] + 1 == a and merged[-1][2] == value:
            merged[-1] = (merged[-1][0], b, value)
        else:
            merged.append((a, b, value))
    output.append(f"pub const {name} = [_]Range{{")
    output.extend(f"    .{{ .first = 0x{a:x}, .last = 0x{b:x}, .value = {value} }}," for a, b, value in merged)
    output.append("};")
(root / "src/terminal/unicode_data.zig").write_text("\n".join(output) + "\n")
fixture = archive.read("auxiliary/GraphemeBreakTest.txt").decode()
(root / "tests/unicode/GraphemeBreakTest.txt").write_text("\n".join(line.rstrip() for line in fixture.splitlines()) + "\n")
# UCD's ReadMe contains the version and authoritative license URL.
(root / "tests/unicode/ReadMe.txt").write_bytes(archive.read("ReadMe.txt"))
