"""Generate box-drawing stroke metadata from Python's Unicode character names."""
from pathlib import Path
import unicodedata

weights = {'LIGHT': 1, 'SINGLE': 1, 'HEAVY': 2, 'DOUBLE': 3}
directions = {'LEFT': (0,), 'RIGHT': (1,), 'UP': (2,), 'DOWN': (3,),
              'HORIZONTAL': (0, 1), 'VERTICAL': (2, 3)}
lines = ['//! Generated by tools/generate_box_data.py; left, right, up, down strokes.',
         'pub const Box = struct { arms: [4]u2, dash: u3 = 0 };',
         'pub const boxes = [_]Box{']
for cp in range(0x2500, 0x2580):
    name = unicodedata.name(chr(cp)).removeprefix('BOX DRAWINGS ')
    arms = [0]*4
    dash = 0
    if 'DIAGONAL' not in name:
        if ' DASH ' in name:
            dash = next(n for word, n in [('DOUBLE', 2), ('TRIPLE', 3), ('QUADRUPLE', 4)] if word+' DASH' in name)
            name = name.replace({2: 'DOUBLE', 3: 'TRIPLE', 4: 'QUADRUPLE'}[dash]+' DASH ', '')
        default = weights.get(name.split()[0], 1)
        for part in name.split(' AND '):
            weight = next((weights[t] for t in part.split() if t in weights), default)
            for token in part.split():
                for d in directions.get(token, ()):
                    arms[d] = weight
    lines.append('    .{ .arms = .{ '+', '.join(map(str, arms))+' }'+(f', .dash = {dash}' if dash else '')+' }, // U+%04X'%cp)
lines.append('};\n')
Path(__file__).resolve().parents[1].joinpath('src/renderer/box_data.zig').write_text('\n'.join(lines))
